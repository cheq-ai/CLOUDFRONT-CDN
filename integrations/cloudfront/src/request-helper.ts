import { CloudFrontRequestEvent, CloudFrontRequestResult } from 'aws-lambda';
import { config } from './config';
import { RTIHttpsLoggerService } from "../../core/services/rti-https-logger.service";
import { RTIHttpsService } from "../../core/services/rti-https.service";
import { RTIHelperService } from "../../core/services/rti-helper.service";
import { name, version } from "../package.json";
import { RequestHeaders, RTIRequest } from "../../core/models/rti-request.model";
import { CloudFrontHeaders, CloudFrontRequest } from 'aws-lambda/common/cloudfront';
import { Action } from '../../core/models/action.model';
import { ActionStrategy } from '../../core/models/action-strategy.model';
import { Ids, RTIResponse } from '../../core/models/rti-response.model';
import { generateDefaultBlockPage } from '../../core/helpers/block-page-helpers';
import { Mode } from '../../core/models/mode.model';

export enum RequestType {
  VIEWER_REQUEST,
  ORIGIN_REQUEST,
}

const logger = new RTIHttpsLoggerService(`${name}-${version}`, config);
const rtiHelperService = new RTIHelperService(config);
const rtiService = new RTIHttpsService(config);

export const handle = async (event: CloudFrontRequestEvent, requestType: RequestType): Promise<CloudFrontRequestResult> => {
    //debugger; // Pause for breakpoints when using SAM - remove for production
    const isDebugEnabled = config.debug;

    if (isDebugEnabled) {
        // event.Records?.[0]?.cf?.config?.requestId is the unique request id generated by CloudFront for each request 
        // and can be used for tracking\debugging (The x-amz-cf-id header in the request represents this id).
        const requestTypeStr = requestType === RequestType.VIEWER_REQUEST ? "Viewer" : requestType === RequestType.ORIGIN_REQUEST ? "Origin" : "Unknown";
        console.log(`Original CF Event (${requestTypeStr} Request Flow): ${JSON.stringify(event)}`);
    }

    // Safe: CloudFront always provides exactly one record with this structure when invoking Lambda@Edge.
    // Would only throw if invoked directly (not via CloudFront), which should not happen in production.
    const cfRequest : CloudFrontRequest = event.Records[0].cf.request;

    // A client must not be able to hand the origin its own verdict: on paths that return without one (ignored
    // path, RTI error, challenge error) its copy would reach the origin. CloudFront lowercases header names.
    delete cfRequest.headers["x-cheq-rti-result"];

    try {
        // Filter out ignored paths. A valid challenge session does not skip RTI: it is checked only when RTI
        // asks for a CAPTCHA (below), so the request still gets a verdict and the x-cheq-rti-result header.
        const requestURL = getRequestUrl(cfRequest);

        if (rtiHelperService.shouldIgnore(requestURL.pathname)) {
            return cfRequest;
        }

        // Build RTI request payload
        const startRTI = Date.now();

        const fetchedHeaders = getHeaders(config.keepHeadersNames, cfRequest.headers);
        // Several Cookie headers are joined with "; ", the cookie separator (", " would glue two cookies together).
        const cookieHeader = cfRequest.headers["cookie"]?.map((kv) => kv.value).join('; ') || "";
        const { duidCookie, pvidCookie, sCookie } = rtiHelperService.parseCookies(cookieHeader);
        let payload: RTIRequest = {
            tagHash: config.tagHash,
            apiKey: config.apiKey,
            // isHeaderNamesOrdered is unknown so kept empty
            channel: "cloudfront-cdn-integration",
            customId1: rtiHelperService.getEventType(requestURL.pathname, cfRequest.method),
            customId2: getCfRequestId(event), // set the cloudfront request id for monitoring
            endUserParams: {
                clientIp: cfRequest.clientIp,
                requestUrl: requestURL.href,
                headerNames: Object.keys(fetchedHeaders).filter(x => fetchedHeaders[x]).join(","),
                method: cfRequest.method,
                headers: fetchedHeaders,
            },
            duidCookie: duidCookie, // Relevant for API version 4.0 and above
            pvidCookie: pvidCookie, // Relevant for API version 4.0 and above
            sCookie: sCookie,       // Relevant for API version 4.1 and above
        };

        // Add JA3 and JA4 fingerprints if available. 
        // These headers are injected by CloudFront at the viewer request stage, 
        // so they will only be available in origin request stage and not in viewer request stage.
        
        // @ts-ignore: This specific line is known to be safe
        payload.endUserParams.headers.cheq_ja3 = cfRequest.headers["cloudfront-viewer-ja3-fingerprint"]?.map((kv) => kv.value).join(', ') || undefined;
        // @ts-ignore: This specific line is known to be safe
        payload.endUserParams.headers.cheq_ja4 = cfRequest.headers["cloudfront-viewer-ja4-fingerprint"]?.map((kv) => kv.value).join(', ') || undefined;

        if (isDebugEnabled) {
            console.log(`RTI Request payload: ${JSON.stringify(payload)}`);
        }

        // Call RTI service
        const rtiResponse = await rtiService.callRTI(payload);

        if (isDebugEnabled) {
            console.log(`RTI Response: ${JSON.stringify(rtiResponse)}`);
        }

        if (config.telemetry) {
            await logger.info(`rti_duration: ${Date.now() - startRTI}`);
        }

        // A request that carries a solved challenge (config.isChallengeAnswer, e.g. the Turnstile form POST) is always
        // handled by the challenge, whatever the verdict: with ALLOW it must not reach the origin as a stray form
        // submission, and under the CAPTCHA strategy it is verified although other POSTs are never challenged.
        // Block, 404 and redirect still win.
        const challengeAnswer = config.challenge !== undefined && (config.isChallengeAnswer?.(cfRequest) ?? false);

        // Get action from RTI response and handle accordingly
        const action = rtiHelperService.getAction(rtiResponse);

        if (isDebugEnabled) {
            const actionName = Action[action];
            console.log(`action upon response: ${actionName ? `${actionName} (${action})` : action}`);
        }

        // If action is not allow, return the corresponding response to client based on action strategy
        if (action !== Action.ALLOW) {
            const actionStrategy = rtiHelperService.getActionStrategy(action);

            if (isDebugEnabled) {
                console.log(`action strategy: ${actionStrategy !== null ? `${ActionStrategy[actionStrategy]} (${actionStrategy})` : "none (should not happen)"} `);
            }

            switch (actionStrategy) {
                case ActionStrategy.ACCESS_DENIED:
                    return {
                        status: '403',
                        headers: { 'content-type': [{ key: 'Content-Type', value: 'text/html;charset=UTF-8' }], ...noStore },
                        body: generateDefaultBlockPage('403', 'Access Denied', rtiResponse.ids, getCfRequestId(event)),
                    };
                case ActionStrategy.NOT_FOUND:
                    return {
                        status: '404',
                        headers: { 'content-type': [{ key: 'Content-Type', value: 'text/html;charset=UTF-8' }], ...noStore },
                        body: generateDefaultBlockPage('404', 'Not Found', rtiResponse.ids, getCfRequestId(event)),
                    };
                case ActionStrategy.REDIRECT:
                    const headers: CloudFrontHeaders = {
                        'x-cheq-cdn-request-id': [{ key: 'x-cheq-cdn-request-id', value: getCfRequestId(event) }],
                        'x-cheq-id': [{ key: 'x-cheq-id', value: rtiResponse.ids.rayId }],
                        'x-cheq-page-view-id': [{ key: 'x-cheq-page-view-id', value: rtiResponse.ids.pageViewId ?? '' }],
                        location: [{ key: 'location', value: config.redirectLocation || "https://www.cheq.ai/" }],
                        ...noStore,
                    };
                    return {
                        status: '302',
                        headers,
                    };
                case ActionStrategy.CAPTCHA:
                    // A challenge page can only answer with a form and a 302, so a POST/PUT/... body (login,
                    // payment, the cross-site 3DS return from the bank) would be lost. Forward it with the verdict
                    // instead: the origin decides, and real visitors are challenged on the GET page before it.
                    // The one POST that is handled here is the challenge's own answer form (challengeAnswer).
                    if (!challengeAnswer && !CHALLENGEABLE_METHODS.includes(cfRequest.method)) {
                        if (isDebugEnabled) {
                            console.log(`${cfRequest.method} request: CAPTCHA not applicable, forwarding with x-cheq-rti-result`);
                        }
                        break;
                    }
                    try {
                        if (config.challenge) {
                            // A visitor who already solved the challenge (valid _cq_se session) is not challenged
                            // again: forward with the real verdict. Only the CAPTCHA is waived, never a block,
                            // 404 or redirect. If validateChallenge throws, the catch below fails open.
                            // An answer is verified even with a session: forwarding it would send the form to the origin.
                            if (!challengeAnswer && await isValidChallenge(cfRequest, isDebugEnabled)) {
                                if (isDebugEnabled) {
                                    console.log("valid challenge session, waiving CAPTCHA");
                                }
                                break;
                            }
                            const challengeResult = await config.challenge(cfRequest, rtiResponse, (headers) => setHeaders(headers, rtiResponse));
                            return challengeResult;
                        }
                        break;
                    } catch (e) {
                        await reportChallengeError(getCfRequestId(event), e);
                        return challengeAnswer ? failOpenAnswer(cfRequest) : cfRequest;
                    }
                default:
                    break;
            }
        }

        // ALLOW with a solved challenge in the request: verify and redirect, never forward the form. Not in
        // MONITORING, which never answers a request itself: the form is sent back to its page unverified instead.
        if (challengeAnswer && config.challenge) {
            if (config.mode === Mode.MONITORING) {
                return failOpenAnswer(cfRequest);
            }
            try {
                return await config.challenge(cfRequest, rtiResponse, (headers) => setHeaders(headers, rtiResponse));
            } catch (e) {
                await reportChallengeError(getCfRequestId(event), e);
                return failOpenAnswer(cfRequest);
            }
        }

        // action is Action.ALLOW, pass headers
        setHeaders(cfRequest.headers, rtiResponse);

        if (isDebugEnabled) {
            console.log(`forwarding to origin with x-cheq-rti-result (${Object.keys(cfRequest.headers).length} headers, body: ${cfRequest.body ? `${cfRequest.body.action ?? "no-action"}/${cfRequest.body.encoding}` : "none"})`);
        }

        return cfRequest;
    } catch (e) {
        const err: Error = e as Error;
        const cfRequestId = getCfRequestId(event);
        console.error(`Error handling request '${cfRequestId}':`, err);
        if (config.logErrors !== false) {
            await logger.error(`Error handling request '${cfRequestId}': ${err.message}`);
        }
    }

    return cfRequest;
};

// A challenge answer (the Turnstile form) cannot fail open by being forwarded: the origin would receive a stray POST.
// It is sent back to the page it came from, without the challenge parameters, as a plain GET (302).
function failOpenAnswer(cfRequest: CloudFrontRequest): CloudFrontRequestResult {
    const pairs = (cfRequest.querystring || "").split("&").filter((pair) => pair !== "");
    const nameOf = (pair: string) => decodeURIComponent(pair.split("=")[0]);
    const isChallengeParam = (name: string) => name === "cf-turnstile-response" || name.startsWith("cheq_");
    const original = pairs.find((pair) => nameOf(pair) === "cheq_original_url")?.split("=").slice(1).join("=");
    let location: string | undefined;
    if (original !== undefined) {
        try {
            const candidate = decodeURIComponent(original);
            // Same-origin path only: no scheme, no "//host", no control characters.
            if (/^\/(?!\/)/.test(candidate) && !/[\u0000-\u001f\u007f]/.test(candidate)) {
                location = candidate;
            }
        } catch { /* malformed: fall back to the request's own path */ }
    }
    if (location === undefined) {
        const kept = pairs.filter((pair) => !isChallengeParam(nameOf(pair)));
        location = kept.length > 0 ? `${cfRequest.uri}?${kept.join("&")}` : cfRequest.uri;
    }
    return { status: '302', headers: { location: [{ key: 'Location', value: location }], ...noStore } };
}

// A challenge error is logged and the request passes through (fail-open), like every other error here.
async function reportChallengeError(cfRequestId: string, e: unknown): Promise<void> {
    const err: Error = e as Error;
    console.error(`Challenge error handling request '${cfRequestId}':`, err);
    if (config.logErrors !== false) {
        await logger.error(`Challenge error handling request '${cfRequestId}': ${err.message}`);
    }
}

async function isValidChallenge(cfRequest : CloudFrontRequest, isDebugEnabled: boolean | undefined): Promise<boolean> {
    const validChallenge = await config.validateChallenge?.(cfRequest, isDebugEnabled) ?? false;
    return validChallenge;
}

// `challenge` without `isChallengeAnswer` means the POSTed Turnstile answer is never recognised: it is forwarded to the
// origin as a stray form and no session is ever issued, so every visitor is challenged forever. Say so at init.
if (config.challenge !== undefined && config.isChallengeAnswer === undefined) {
    console.warn("config.challenge is set but config.isChallengeAnswer is not: wire isChallengeAnswer (e.g. turnstileChallenge.isChallengeAnswer) or the challenge answer will never be verified");
}

// Only these methods can be challenged without losing the request: see the CAPTCHA case in handle().
const CHALLENGEABLE_METHODS = ['GET', 'HEAD'];

// Block and redirect answers must never be cached: on the origin-request trigger CloudFront caches what the Lambda
// returns (403/404 for 10 s by default), so one bot's block page would be served to every visitor of that URL.
const noStore: CloudFrontHeaders = { 'cache-control': [{ key: 'Cache-Control', value: 'no-store, no-cache, must-revalidate' }] };

function getRequestUrl(cfRequest : CloudFrontRequest): URL {
    const host = (cfRequest.headers["host"]?.map((kv) => kv.value) || "").join(', ');

    let url = `https://${host}${cfRequest.uri}`;

    if (cfRequest.querystring) {
        url += `?${cfRequest.querystring}`;
    }

    return new URL(url);
}

function setHeaders(headers: CloudFrontHeaders, rtiResponse: RTIResponse) {
    // Add RTI result header to the request that will be sent to the origin. 
    // This can be used by the origin for debugging, logging, or making decisions based on the RTI result.
    // On the request to the origin it is only visible in the browser if the origin echoes it back. It is also passed to
    // config.challenge as addRtiResultHeader: the Turnstile example adds it to the 302 after a solved challenge, which the browser does see.

    headers["x-cheq-rti-result"] = [{ key: 'x-cheq-rti-result', value: rtiHelperService.buildRtiResultHeader(rtiResponse) }];
}

function getHeaders(keepHeadersNames: string[], headers: CloudFrontHeaders): RequestHeaders {
    const result: RequestHeaders = {};
    const headerKeys = keepHeadersNames && keepHeadersNames.length > 0 ? keepHeadersNames : Object.keys(headers);
    
    for (const headerName of headerKeys) {
        const headerValues = headers[headerName];
        if (headerValues) {
            result[headerName] = headerValues.map((kv) => kv.value).join(', ');
        }
    }
    
    return result;
}

function getCfRequestId(event: CloudFrontRequestEvent): string {
    try {
        // This id is represented by CloudFront as x-amz-cf-id header in the request and can  be used for tracking\debugging.
        const cfRequestId = event.Records?.[0]?.cf?.config?.requestId ?? "unknown_request_id";
        return cfRequestId;
    } catch (e) {
        const err: Error = e as Error;
        return `on_error_request_id (${err.message})`;
    }
}
